# `theme`: declarative colour presets rendered into every app's config.
# Presets: themes/*.json (baked in) + $XDG_CONFIG_HOME/theme/themes/*.json (override by id).
# State:   $XDG_STATE_HOME/theme/ (current.json = resolved preset, written last; Quickshell watches it).
# Placeholders @themes@ is substituted by pkgs/theme.nix.

builtin_dir=@themes@
tpl_dir=$builtin_dir/templates
home=${HOME:?HOME is not set}
state_base=${XDG_STATE_HOME:-$home/.local/state}
conf_base=${XDG_CONFIG_HOME:-$home/.config}
state_dir=$state_base/theme
user_dir=$conf_base/theme/themes
default_id=mocha
# shellcheck disable=SC2016  # literal backticks
marker='generated by `theme`'

die() { echo "theme: $*" >&2; exit 1; }

# Schema check, prints nothing; exit status only. $1 = file, $2 = expected id.
valid_preset() {
  jq -e --arg id "$2" '
    def hex: type == "string" and test("^#[0-9a-fA-F]{6}$");
    ["base","mantle","crust","surface0","surface1","surface2","overlay0","subtext0","text",
     "blue","mauve","green","yellow","peach","red","teal","pink","lavender","sky","sapphire",
     "maroon","rosewater","flamingo"] as $keys
    | .id == $id and (.name | type == "string")
      and (.colors | type == "object") and (.colors as $c | $keys | all(. as $k | $c[$k] | hex))
      and (.colors[.accent] | hex)
      and ((.barOpacity // 0.95) | type == "number" and . >= 0 and . <= 1)
      and ((.iconWeight // "regular") | IN("thin", "light", "regular", "bold", "fill"))
  ' "$1" >/dev/null 2>&1
}

# Path of the effective file for an id (user override wins), or empty.
preset_path() {
  local id=$1 f
  [[ $id =~ ^[a-z0-9][a-z0-9_-]*$ ]] || return 0
  for f in "$user_dir/$id.json" "$builtin_dir/$id.json"; do
    if [ -f "$f" ] && valid_preset "$f" "$id"; then echo "$f"; return 0; fi
  done
}

# Preset JSON with defaults filled in.
load_preset() {
  local f
  f=$(preset_path "$1")
  [ -n "$f" ] || die "unknown or invalid theme '$1' (see: theme list)"
  jq -c '{variant: "dark", barOpacity: 0.95, iconWeight: "regular"} + .' "$f"
}

all_ids() {
  local f id
  for f in "$builtin_dir"/*.json "$user_dir"/*.json; do
    [ -f "$f" ] || continue
    id=$(basename "$f" .json)
    if [ -n "$(preset_path "$id")" ]; then echo "$id"; else echo "theme: skipping invalid preset $f" >&2; fi
  done | sort -u
}

current_id() {
  local id=""
  [ -f "$state_dir/current.json" ] && id=$(jq -er '.id' "$state_dir/current.json" 2>/dev/null) || true
  echo "${id:-$default_id}"
}

# Atomic replace within the target's directory; returns 0 if the content changed.
write_file() {
  local dest=$1 tmp
  mkdir -p "$(dirname "$dest")"
  tmp=$(mktemp "$dest.XXXXXX")
  cat >"$tmp"
  chmod 644 "$tmp"
  if [ -f "$dest" ] && cmp -s "$tmp" "$dest"; then rm -f "$tmp"; return 1; fi
  mv -f "$tmp" "$dest"
}

render() { # $1 = template name, $2 = placeholder map (json)
  local out
  out=$(jq -Rsj --argjson m "$2" '
    reduce ($m | keys_unsorted[]) as $k (.; split("{{" + $k + "}}") | join($m[$k] | tostring))
  ' "$tpl_dir/$1")
  if [[ $out == *"{{"* ]]; then die "template $1 has unresolved placeholders"; fi
  printf '%s\n' "$out"
}

# GTK css lives in the real ~/.config (not a repo symlink); keep a hand-written one once.
write_gtk() { # $1 = dest, stdin = css
  local dest=$1 css
  css=$(cat)
  if [ -f "$dest" ] && ! grep -qF "$marker" "$dest" && [ ! -e "$dest.bak" ]; then
    cp -p "$dest" "$dest.bak"
  fi
  printf '%s\n' "$css" | write_file "$dest"
}

# Reload apps only against the real XDG dirs (sandboxed tests must not poke the session).
reload_apps() {
  [ "${THEME_NO_RELOAD:-0}" = 1 ] && return 0
  [ "$state_base" = "$home/.local/state" ] && [ "$conf_base" = "$home/.config" ] || return 0
  # ghostty reloads its config (and config-file includes) on SIGUSR2
  pkill -USR2 -u "$(id -u)" -f '^(.*/)?\.?ghostty(-wrapped)?( |$)' 2>/dev/null || true
  # niri hot-reloads on file change; the explicit call covers the symlinked include
  niri msg action load-config-file >/dev/null 2>&1 || true
}

apply_preset() { # $1 = id, $2 = force reload (0/1)
  local preset map changed=$2
  preset=$(load_preset "$1")
  map=$(jq -c '.colors + {id, name, accent_name: .accent, accent: .colors[.accent],
                          barOpacity: (.barOpacity | tostring), iconWeight}' <<<"$preset")
  mkdir -p "$state_dir"
  render ghostty.conf "$map" | write_file "$state_dir/ghostty.conf" && changed=1
  render niri.kdl "$map" | write_file "$state_dir/niri.kdl" && changed=1
  render zathura.conf "$map" | write_file "$state_dir/zathura.conf" && changed=1
  render colors.env "$map" | write_file "$state_dir/colors.env" && changed=1
  render gtk.css "$map" | write_gtk "$conf_base/gtk-3.0/gtk.css" && changed=1
  render gtk.css "$map" | write_gtk "$conf_base/gtk-4.0/gtk.css" && changed=1
  [ "$changed" = 1 ] && reload_apps
  # last: the shell recolors when this changes, apps are already themed
  jq . <<<"$preset" | write_file "$state_dir/current.json" || true
}

cmd=${1:-}
case $cmd in
  list)
    if [ "${2:-}" = "--json" ]; then
      while read -r id; do
        f=$(preset_path "$id")
        builtin=false
        [ "$f" = "$builtin_dir/$id.json" ] && builtin=true
        load_preset "$id" | jq -c --argjson b "$builtin" '. + {builtin: $b}'
      done < <(all_ids) | jq -s .
    else
      all_ids
    fi
    ;;
  current) current_id ;;
  set)
    [ -n "${2:-}" ] || die "usage: theme set <id>"
    apply_preset "$2" 1
    ;;
  next)
    mapfile -t ids < <(all_ids)
    [ "${#ids[@]}" -gt 0 ] || die "no themes found"
    cur=$(current_id)
    next=${ids[0]}
    for i in "${!ids[@]}"; do
      if [ "${ids[$i]}" = "$cur" ]; then next=${ids[$(((i + 1) % ${#ids[@]}))]}; fi
    done
    apply_preset "$next" 1
    echo "$next"
    ;;
  apply)
    id=$(current_id)
    if [ -z "$(preset_path "$id")" ]; then
      echo "theme: '$id' is gone, falling back to $default_id" >&2
      id=$default_id
    fi
    apply_preset "$id" 0
    ;;
  *)
    echo "usage: theme list [--json] | current | set <id> | next | apply" >&2
    exit 2
    ;;
esac
