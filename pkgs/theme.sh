# `theme`: declarative colour presets rendered into every app's config.
# Presets: themes/*.json (baked in) + $XDG_CONFIG_HOME/theme/themes/*.json (override by id).
# State:   $XDG_STATE_HOME/theme/ (current.json = resolved preset, written last; Quickshell watches it).
# Placeholders @themes@ is substituted by pkgs/theme.nix.

builtin_dir=@themes@
tpl_dir=$builtin_dir/templates
adw_dir=@adwgtk3@
home=${HOME:?HOME is not set}
state_base=${XDG_STATE_HOME:-$home/.local/state}
conf_base=${XDG_CONFIG_HOME:-$home/.config}
state_dir=$state_base/theme
user_dir=$conf_base/theme/themes
themes_dir=${XDG_DATA_HOME:-$home/.local/share}/themes
default_id=mocha
# shellcheck disable=SC2016  # literal backticks
marker='generated by `theme`'

die() { echo "theme: $*" >&2; exit 1; }

# Schema check, prints nothing; exit status only. $1 = file, $2 = expected id.
valid_preset() {
  jq -e --arg id "$2" '
    def hex: type == "string" and test("^#[0-9a-fA-F]{6}$");
    ["base","mantle","crust","surface0","surface1","surface2","overlay0","subtext0","text",
     "blue","mauve","green","yellow","peach","red","teal","pink","lavender","sky","sapphire",
     "maroon","rosewater","flamingo"] as $keys
    | .id == $id and (.name | type == "string")
      and (.colors | type == "object") and (.colors as $c | $keys | all(. as $k | $c[$k] | hex))
      and (.colors[.accent] | hex)
      and ((.barOpacity // 0.85) | type == "number" and . >= 0 and . <= 1)
      and ((.iconWeight // "regular") | IN("thin", "light", "regular", "bold", "fill"))
      and ((.variant // "dark") | IN("dark", "light"))
      and ((.variant // "dark") | IN("dark", "light"))
  ' "$1" >/dev/null 2>&1
}

# Path of the effective file for an id (user override wins), or empty.
preset_path() {
  local id=$1 f
  [[ $id =~ ^[a-z0-9][a-z0-9_-]*$ ]] || return 0
  for f in "$user_dir/$id.json" "$builtin_dir/$id.json"; do
    if [ -f "$f" ] && valid_preset "$f" "$id"; then echo "$f"; return 0; fi
  done
}

# Preset JSON with defaults filled in.
load_preset() {
  local f
  f=$(preset_path "$1")
  [ -n "$f" ] || die "unknown or invalid theme '$1' (see: theme list)"
  jq -c '{variant: "dark", barOpacity: 0.85, iconWeight: "regular"} + .' "$f"
}

all_ids() {
  local f id
  for f in "$builtin_dir"/*.json "$user_dir"/*.json; do
    [ -f "$f" ] || continue
    id=$(basename "$f" .json)
    if [ -n "$(preset_path "$id")" ]; then echo "$id"; else echo "theme: skipping invalid preset $f" >&2; fi
  done | sort -u
}

current_id() {
  local id=""
  [ -f "$state_dir/current.json" ] && id=$(jq -er '.id' "$state_dir/current.json" 2>/dev/null) || true
  echo "${id:-$default_id}"
}

# Atomic replace within the target's directory; returns 0 if the content changed.
write_file() {
  local dest=$1 tmp
  mkdir -p "$(dirname "$dest")"
  tmp=$(mktemp "$dest.XXXXXX")
  cat >"$tmp"
  chmod 644 "$tmp"
  if [ -f "$dest" ] && cmp -s "$tmp" "$dest"; then rm -f "$tmp"; return 1; fi
  mv -f "$tmp" "$dest"
}

render() { # $1 = template name, $2 = placeholder map (json)
  local out
  out=$(jq -Rsj --argjson m "$2" '
    reduce ($m | keys_unsorted[]) as $k (.; split("{{" + $k + "}}") | join($m[$k] | tostring))
  ' "$tpl_dir/$1")
  if [[ $out == *"{{"* ]]; then die "template $1 has unresolved placeholders"; fi
  printf '%s\n' "$out"
}

# GTK css lives in the real ~/.config (not a repo symlink); keep a hand-written one once.
write_gtk() { # $1 = dest, stdin = css
  local dest=$1 css
  css=$(cat)
  if [ -f "$dest" ] && ! grep -qF "$marker" "$dest" && [ ! -e "$dest.bak" ]; then
    cp -p "$dest" "$dest.bak"
  fi
  printf '%s\n' "$css" | write_file "$dest"
}

# GTK3 apps (Chrome in GTK mode, Thunar) read ~/.config/gtk-3.0/gtk.css only at startup, but they
# reload live when the GTK theme *name* changes. So each preset becomes a tiny real theme that
# imports adw-gtk3 and overrides its colours, named after a hash of its CSS: switching presets (or
# editing one) changes the name, dconf/the Settings portal announce it, and running apps recolour.
write_gtk_theme() { # $1 = name, $2 = adw-gtk3 variant dir name, stdin = colour css
  local dir=$themes_dir/$1
  mkdir -p "$dir/gtk-3.0"
  ln -sfn "$adw_dir/$2/gtk-4.0" "$dir/gtk-4.0"
  printf "[Desktop Entry]\nType=X-GNOME-Metatheme\nName=%s\nComment=%s\n" "$1" "$marker" | write_file "$dir/index.theme" || true
  { printf "@import url(\"file://%s/%s/gtk-3.0/gtk.css\");\n\n" "$adw_dir" "$2"; cat; } | write_file "$dir/gtk-3.0/gtk.css"
}
# Drop generated themes other than $1 (after apps have switched away from them)
prune_gtk_themes() {
  local d
  for d in "$themes_dir"/theme-*; do
    [ -d "$d" ] && [ "$d" != "$themes_dir/$1" ] && grep -qF "$marker" "$d/index.theme" 2>/dev/null && rm -rf "$d"
  done
  return 0
}

# Reload apps only against the real XDG dirs (sandboxed tests must not poke the session).
reload_apps() {
  [ "${THEME_NO_RELOAD:-0}" = 1 ] && return 0
  [ "$state_base" = "$home/.local/state" ] && [ "$conf_base" = "$home/.config" ] || return 0
  # ghostty reloads its config (and config-file includes) on SIGUSR2
  pkill -USR2 -u "$(id -u)" -f '^(.*/)?\.?ghostty(-wrapped)?( |$)' 2>/dev/null || true
  # niri hot-reloads on file change; the explicit call covers the symlinked include
  niri msg action load-config-file >/dev/null 2>&1 || true
}

# System-wide light/dark: the Settings portal (libadwaita, GTK4, Chrome, Electron) follows color-scheme live.
set_system_scheme() { # $1 = dark|light, $2 = "<gtk theme> <icon theme>"
  [ "${THEME_NO_RELOAD:-0}" = 1 ] && return 0
  [ "$state_base" = "$home/.local/state" ] && [ "$conf_base" = "$home/.config" ] || return 0
  local scheme=prefer-dark gtk icons
  [ "$1" = light ] && scheme=prefer-light
  read -r gtk icons <<<"$2"
  local p=/org/gnome/desktop/interface
  dconf write "$p/color-scheme" "'$scheme'" 2>/dev/null || true
  dconf write "$p/gtk-theme" "'$gtk'" 2>/dev/null || true
  dconf write "$p/icon-theme" "'$icons'" 2>/dev/null || true
}

apply_preset() { # $1 = id, $2 = force reload (0/1)
  local preset map changed=$2
  preset=$(load_preset "$1")
  map=$(jq -c '.colors + {id, name, accent_name: .accent, accent: .colors[.accent],
                          barOpacity: (.barOpacity | tostring), iconWeight,
                          prefer_dark: (if .variant == "light" then "0" else "1" end),
                          gtk_theme: (if .variant == "light" then "adw-gtk3" else "adw-gtk3-dark" end),
                          icon_theme: (if .variant == "light" then "Papirus-Light" else "Papirus-Dark" end),
                          ansi0: (if .variant == "light" then .colors.subtext0 else .colors.surface1 end),
                          ansi8: (if .variant == "light" then .colors.overlay0 else .colors.surface2 end),
                          ansi7: (if .variant == "light" then .colors.surface2 else .colors.subtext0 end),
                          ansi15: (if .variant == "light" then .colors.surface1 else .colors.text end)}' <<<"$preset")
  # The generated GTK theme replaces adw-gtk3 as the theme name (see write_gtk_theme)
  local css gtk_name
  css=$(render gtk.css "$map")
  gtk_name="theme-$(jq -r .id <<<"$preset")-$(printf "%s" "$css" | md5sum | cut -c1-8)"
  write_gtk_theme "$gtk_name" "$(jq -r .gtk_theme <<<"$map")" <<<"$css" && changed=1
  map=$(jq -c --arg n "$gtk_name" ".gtk_theme = \$n" <<<"$map")
  mkdir -p "$state_dir"
  render ghostty.conf "$map" | write_file "$state_dir/ghostty.conf" && changed=1
  render niri.kdl "$map" | write_file "$state_dir/niri.kdl" && changed=1
  render zathura.conf "$map" | write_file "$state_dir/zathura.conf" && changed=1
  render colors.env "$map" | write_file "$state_dir/colors.env" && changed=1
  # GTK3 colours now live in the theme above; the user css is left as an empty stub, because
  # anything here is loaded once at startup and would pin running apps to stale colours
  printf "/* %s: GTK3 colours live in %s, so running apps recolour live */\n" "$marker" "$themes_dir/$gtk_name" | write_gtk "$conf_base/gtk-3.0/gtk.css" && changed=1
  render gtk.css "$map" | write_gtk "$conf_base/gtk-4.0/gtk.css" && changed=1
  render gtk-settings.ini "$map" | write_gtk "$conf_base/gtk-3.0/settings.ini" && changed=1
  render gtk-settings.ini "$map" | write_gtk "$conf_base/gtk-4.0/settings.ini" && changed=1
  set_system_scheme "$(jq -r '.variant' <<<"$preset")" "$(jq -r '.gtk_theme + " " + .icon_theme' <<<"$map")"
  [ "$changed" = 1 ] && reload_apps
  prune_gtk_themes "$gtk_name"
  # last: the shell recolors when this changes, apps are already themed
  jq . <<<"$preset" | write_file "$state_dir/current.json" || true
}

cmd=${1:-}
case $cmd in
  list)
    if [ "${2:-}" = "--json" ]; then
      while read -r id; do
        f=$(preset_path "$id")
        builtin=false
        [ "$f" = "$builtin_dir/$id.json" ] && builtin=true
        load_preset "$id" | jq -c --argjson b "$builtin" '. + {builtin: $b}'
      done < <(all_ids) | jq -s .
    else
      all_ids
    fi
    ;;
  current) current_id ;;
  set)
    [ -n "${2:-}" ] || die "usage: theme set <id>"
    apply_preset "$2" 1
    ;;
  next)
    mapfile -t ids < <(all_ids)
    [ "${#ids[@]}" -gt 0 ] || die "no themes found"
    cur=$(current_id)
    next=${ids[0]}
    for i in "${!ids[@]}"; do
      if [ "${ids[$i]}" = "$cur" ]; then next=${ids[$(((i + 1) % ${#ids[@]}))]}; fi
    done
    apply_preset "$next" 1
    echo "$next"
    ;;
  apply)
    id=$(current_id)
    if [ -z "$(preset_path "$id")" ]; then
      echo "theme: '$id' is gone, falling back to $default_id" >&2
      id=$default_id
    fi
    apply_preset "$id" 0
    ;;
  *)
    echo "usage: theme list [--json] | current | set <id> | next | apply" >&2
    exit 2
    ;;
esac
